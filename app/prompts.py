def build_few_shot_block() -> str:
    lines = ["Примеры (синтетические, учат паттерны):"]
    for label, dialogue in FEW_SHOT_EXAMPLES:
        lines.append(f"\n--- label: {label} ---\n{dialogue}")
    return "\n".join(lines)


