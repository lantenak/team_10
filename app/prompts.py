def build_few_shot_block() -> str:
    lines = ["## Примеры (синтетические паттерны)"]
    for label, dialogue in FEW_SHOT_EXAMPLES:
        tag = "null (clean)" if label == "clean" else label
        lines.append(f"\n### Пример → {tag}\n{dialogue}")
    return "\n".join(lines)


FEW_SHOT_BLOCK = build_few_shot_block()


def build_classification_prompt(dialogue_text: str, *, max_dialogue_chars: int = 6000) -> str:
    if len(dialogue_text) > max_dialogue_chars:
        dialogue_text = dialogue_text[:max_dialogue_chars] + "\n...[обрезано]"

    return f"""{CLASSIFICATION_INSTRUCTIONS}

{CATEGORY_GUIDE}

{DISAMBIGUATION_RULES}

{FEW_SHOT_BLOCK}

---

## Новый диалог для классификации

{dialogue_text}

---

Перед ответом проверь:
• Нарушение исходит от user, не от support/chatbot?
• Это не легитимный свой счёт / баг приложения / ретроспектива без давления на новый перевод?
• Если red flag — выбрана одна самая подходящая категория?

Ответь ТОЛЬКО JSON (без ```):
{{"category": "<policy_manipulation|adversarial_attack|identity_deception|transaction_coercion|information_extraction|scope_violation>" | null, "reason": "<одно предложение: почему>"}}"""
